// Helper to reproducibly generate time-series observations for a patient
export function generatePatientTimeSeries(patient: PatientEHR, count: number = 30): WearableObservation[] {
  const observations: WearableObservation[] = [];
  const baseTimestamp = Date.now() - (count * 5 * 60 * 1000); // 5-minute intervals backwards

  // Deterministic seed based on patient ID digits
  const seed = parseInt(patient.patientId.replace(/\D/g, ''), 10) || 1000;

  for (let i = 0; i < count; i++) {
    const timeOffsetMs = i * 5 * 60 * 1000;
    const observationTime = new Date(baseTimestamp + timeOffsetMs).toISOString();

    // Cyclic circadian pattern + physiological drift
    const hourOfDay = (new Date(baseTimestamp + timeOffsetMs).getUTCHours()) % 24;
    const circadianMod = Math.sin((hourOfDay - 6) * (Math.PI / 12)); // peaks in afternoon

    // Patient baseline factors
    const isHighRisk = patient.baselineRiskCategory === 'High' || patient.baselineRiskCategory === 'Elevated';
    
    // Simulating elevated strain episodes in high risk patients
    const isStressEpisode = isHighRisk && (i >= count - 8);

    let hrBase = patient.restingHeartRateBaseline + (circadianMod * 6);
    let hrvBase = patient.restingHrvBaseline - (circadianMod * 4);
    let spo2 = 97 + Math.sin(i * 0.4);
    let activity: ActivityIntensity = 'Sedentary';
    let stepIncrement = 30 + Math.floor(Math.abs(Math.sin(i * 0.8)) * 120);

    if (isStressEpisode) {
      hrBase += 22 + Math.sin(i * 1.5) * 8; // Tachycardia episode
      hrvBase = Math.max(13, hrvBase - 12); // Low HRV autonomic strain
      spo2 = Math.max(92, 95 - Math.abs(Math.cos(i * 0.5) * 2));
      activity = 'Rest'; // Elevated HR while resting = major flag
    } else {
      // Natural variations
      const noise = Math.sin((seed + i) * 1.7) * 4;
      hrBase += noise;
      hrvBase = Math.max(16, hrvBase + Math.cos((seed + i) * 1.3) * 5);
      if (i % 6 === 0) activity = 'Light';
      if (i % 14 === 0) activity = 'Moderate';
    }

    const hr = Math.round(Math.max(48, Math.min(150, hrBase)));
    const hrv = Math.round(Math.max(12, Math.min(95, hrvBase)));
    const roundedSpo2 = Math.min(100, Math.max(90, Math.round(spo2 * 10) / 10));

    // Simulated alert triggered if high HR during rest combined with low HRV
    const isAlert = hr > 95 && hrv < 24 && (activity === 'Rest' || activity === 'Sedentary');
    const alertReason = isAlert 
      ? 'Autonomic Dysregulation: Disproportionate Resting Tachycardia & Depressed HRV (RMSSD < 25ms)'
      : undefined;

    const quality: SignalQuality = (i % 19 === 0) ? 'Acceptable' : 'Optimal';

    observations.push({
      id: `${patient.patientId}-obs-${i}`,
      patientId: patient.patientId,
      timestamp: observationTime,
      heartRate: hr,
      hrvRmssd: hrv,
      sleepDurationHours: 6.8 + (Math.sin(seed + i) * 1.2),
      deepSleepPercent: Math.round(18 + Math.cos(i) * 5),
      sleepEfficiencyPercent: Math.round(82 + Math.sin(i * 0.5) * 8),
      stepCountCumulative: 4200 + (i * stepIncrement),
      activityIntensity: activity,
      spo2: roundedSpo2,
      skinTempDevC: Math.round((Math.sin(i * 0.3) * 0.4) * 100) / 100,
      signalQuality: quality,
      isSimulatedAlert: isAlert,
      simulatedAlertReason: alertReason
    });
  }

  return observations;
}
